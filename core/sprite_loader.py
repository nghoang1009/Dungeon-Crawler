    def resolve_name(self, name: str) -> tuple[str, int, int] | None:
        """Finds (sheet_name, row, col) for a given sprite name."""
        clean = name.strip().lower()
        if clean in self._name_to_loc:
            return self._name_to_loc[clean]

        slug = clean.replace(" ", "_").replace("-", "_")
        if slug in self._name_to_loc:
            return self._name_to_loc[slug]

        alphanumeric = re.sub(r"[^a-z0-9]", "", clean)
        if alphanumeric in self._name_to_loc:
            return self._name_to_loc[alphanumeric]

        # Substring search in registered names
        for k, loc in self._name_to_loc.items():
            if clean in k or k in clean:
                return loc

        return None

    def _crop_sprite(self, sheet_name: str, row: int, col: int, src_size: int = SPRITE_SRC_SIZE, dest_size: int = TILE_SIZE) -> pygame.Surface:
        """
        Crops exact 32x32 sub-surface from sprite sheet (row: 1-indexed, col: 0-indexed).
        Uses point sampling nearest-neighbor scaling preserving crisp pixel art.
        """
        key = f"{sheet_name}_{row}_{col}_{src_size}_{dest_size}"
        if key in self._cache:
            return self._cache[key]

        sheet = self._sheets.get(sheet_name)
        if not sheet:
            surf = pygame.Surface((dest_size, dest_size), pygame.SRCALPHA)
            surf.fill((60, 60, 80))
            return surf

        x = col * src_size
        y = (row - 1) * src_size

        sheet_w, sheet_h = sheet.get_size()
        if x + src_size > sheet_w or y + src_size > sheet_h:
            surf = pygame.Surface((dest_size, dest_size), pygame.SRCALPHA)
            surf.fill((80, 50, 70))
            return surf

        sub = pygame.Surface((src_size, src_size), pygame.SRCALPHA)
        sub.blit(sheet, (0, 0), (x, y, src_size, src_size))

        if src_size != dest_size:
            scaled = pygame.transform.scale(sub, (dest_size, dest_size))
        else:
            scaled = sub

        self._cache[key] = scaled
        return scaled

    def get_sprite(self, name_or_sheet: str, row: int | None = None, col: int | None = None, src_size: int = SPRITE_SRC_SIZE, dest_size: int = TILE_SIZE) -> pygame.Surface:
        """
        Flexible sprite retrieval:
        1. By name: get_sprite("Knight", dest_size=32) or get_sprite("Goblin")
        2. By coordinates: get_sprite("tiles.png", row=3, col=0, src_size=32, dest_size=32)
        """
        if row is not None and col is not None:
            return self._crop_sprite(name_or_sheet, row, col, src_size, dest_size)

        # Name-based lookup
        target_size = dest_size if row is None else row
        loc = self.resolve_name(name_or_sheet)
        if loc:
            sheet_name, r, c = loc
            return self._crop_sprite(sheet_name, r, c, SPRITE_SRC_SIZE, target_size)

        # Fallback empty surface
        surf = pygame.Surface((target_size, target_size), pygame.SRCALPHA)
        surf.fill((70, 70, 90))
        return surf

    def get_sprite_by_name(self, name: str, dest_size: int = TILE_SIZE) -> pygame.Surface:
        """Direct lookup of any sprite by exact or normalized TXT name."""
        return self.get_sprite(name, dest_size=dest_size)

    # 1. TILES MAPPINGS (resolved from TXT mappings)
    def get_tile_wall(self, style: int = 1) -> pygame.Surface:
        asset = self._tiles.get("wall_face")
