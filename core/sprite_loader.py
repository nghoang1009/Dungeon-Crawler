    # Shared procedural animation helpers. Every base sprite faces LEFT (see settings.SPRITES_FACE_LEFT),
    # so "forward" is -x here and the mirrored copy handles right-facing.
    @staticmethod
    def _walk_frames(base: pygame.Surface, size: int) -> list[pygame.Surface]:
        """4-frame waddle: squash on contact, rise on passing, with a small side sway; feet stay on the ground."""
        steps = [(0.90, 0, -1), (1.00, -2, -1), (0.90, 0, 1), (1.00, -2, 1)]  # (height scale, rise, sway)
        frames = []
        for scale_h, rise, sway in steps:
            surf = pygame.Surface((size, size), pygame.SRCALPHA)
            h = max(1, int(size * scale_h))
            body = base if h == size else pygame.transform.scale(base, (size, h))
            surf.blit(body, (sway, size - h + rise))
            frames.append(surf)
        return frames

    @staticmethod
    def _attack_frames(base: pygame.Surface, size: int) -> list[pygame.Surface]:
        """Lunge forward (to the left) over four frames."""
        frames = []
        for i in range(4):
            surf = pygame.Surface((size, size), pygame.SRCALPHA)
            surf.blit(base, (-i * 2, 0))
            frames.append(surf)
        return frames

    # 2. MONSTER FRAMES (generated from base sprite resolved by name with caching)
    def get_enemy_frames(self, enemy_name: str, dest_size: int = TILE_SIZE) -> dict[str, list[pygame.Surface]]:
        if enemy_name in self._boss_frames:
            return self.get_boss_frames(enemy_name)

        cache_key = f"anim_enemy_{enemy_name}_{dest_size}"
        if cache_key in self._cache:
            return self._cache[cache_key]

        base_sprite = self.get_sprite(enemy_name, dest_size=dest_size)

        frames = {"idle": [], "walk": [], "attack": [], "telegraph": [], "hurt": [], "dead": []}

        # Idle frames (breathing animation)
        for i in range(4):
            surf = pygame.Surface((dest_size, dest_size), pygame.SRCALPHA)
            off_y = int(math.sin(i * math.pi / 2) * 1.5)
            surf.blit(base_sprite, (0, off_y))
            frames["idle"].append(surf)

        frames["walk"] = self._walk_frames(base_sprite, dest_size)
        frames["attack"] = self._attack_frames(base_sprite, dest_size)

        # Telegraph frame (Red aura warning)
        surf_tele = pygame.Surface((dest_size, dest_size), pygame.SRCALPHA)
        surf_tele.blit(base_sprite, (0, 0))
        glow_layer = pygame.Surface((dest_size, dest_size), pygame.SRCALPHA)
        pygame.draw.circle(glow_layer, (255, 40, 40, 140), (dest_size // 2, dest_size // 2), dest_size // 2)
        surf_tele.blit(glow_layer, (0, 0))
        frames["telegraph"].append(surf_tele)

        # Hurt frame (Crisp white flash)
        surf_hurt = pygame.Surface((dest_size, dest_size), pygame.SRCALPHA)
        surf_hurt.blit(base_sprite, (0, 0))
        # Whiten only the opaque pixels (an RGBA add would turn the whole transparent square white)
        surf_hurt.fill((200, 200, 200, 0), special_flags=pygame.BLEND_RGB_ADD)
        frames["hurt"].append(surf_hurt)

        # Dead frame (Rotated 90 deg)
        surf_dead = pygame.transform.rotate(base_sprite, 90)
        dead_final = pygame.Surface((dest_size, dest_size), pygame.SRCALPHA)
        dead_final.blit(surf_dead, (0, 4))
        frames["dead"].append(dead_final)

        self._cache[cache_key] = frames
        return frames

    # 3. PLAYER FRAMES (Knight, Archer, Mage - resolved by name from TXT with caching)
    def get_player_frames(self, player_class: str = "Knight", dest_size: int = TILE_SIZE) -> dict[str, list[pygame.Surface]]:
        cache_key = f"anim_player_{player_class}_{dest_size}"
        if cache_key in self._cache:
            return self._cache[cache_key]

        base_sprite = self.get_sprite(player_class, dest_size=dest_size)

        frames = {"idle": [], "walk": [], "attack": [], "hurt": [], "dead": []}

        for i in range(4):
            surf = pygame.Surface((dest_size, dest_size), pygame.SRCALPHA)
            off_y = int(math.sin(i * math.pi / 2) * 1.5)
            surf.blit(base_sprite, (0, off_y))
            frames["idle"].append(surf)

        frames["walk"] = self._walk_frames(base_sprite, dest_size)
        frames["attack"] = self._attack_frames(base_sprite, dest_size)

        surf_hurt = pygame.Surface((dest_size, dest_size), pygame.SRCALPHA)
        surf_hurt.blit(base_sprite, (0, 0))
        # Whiten only the opaque pixels (an RGBA add would turn the whole transparent square white)
        surf_hurt.fill((200, 200, 200, 0), special_flags=pygame.BLEND_RGB_ADD)
        frames["hurt"].append(surf_hurt)

        surf_dead = pygame.transform.rotate(base_sprite, 90)
        dead_final = pygame.Surface((dest_size, dest_size), pygame.SRCALPHA)
        dead_final.blit(surf_dead, (0, 4))
        frames["dead"].append(dead_final)

        self._cache[cache_key] = frames
        return frames

    # 4. ITEM SPRITES (resolved by name from TXT)
    def get_item_sprite(self, item_name: str, dest_size: int = TILE_SIZE) -> pygame.Surface:
        return self.get_sprite(item_name, dest_size=dest_size)
