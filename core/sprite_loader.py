import pygame
import os
import re
import math
from settings import TILE_SIZE

SPRITE_SRC_SIZE = 32  # Standard native 32x32 pixel dimensions for all project PNG sprite sheets


class SpriteSheetLoader:
    """
    Singleton Asset Loader reading TXT mappings and extracting/caching pixel-art surfaces
    from project's PNG sprite sheets at exact 32x32 resolution:
    - tiles.png <-> tiles.txt (walls, floors, doors, stairs, chests, traps, barrels, rocks)
    - monsters.png <-> monsters.txt (goblins, orcs, skeletons, mages, golems, bosses)
    - items.png <-> items.txt (swords, axes, spears, bows, staves, potions, rings, coins)
    - rogues.png <-> rogues.txt (knights, rangers, wizards, blacksmiths, merchants, clerics)
    - animated-tiles.png <-> animated-tiles.txt
    - autotiles.png <-> autotiles.txt
    - animals.png <-> animals.txt
    """
    _instance = None
    _sheets = {}
    _cache = {}
    _name_to_loc = {}  # normalized_name -> (sheet_filename, row, col)
    _tiles = {}        # assets/tiles/<name>.png (dungeon look from demo_dungeon.png)
    _boss_frames = {}  # assets/bosses/<name>_<frame>.png -> {name: [frames]}

    def __new__(cls):
        if cls._instance is None:
            cls._instance = super(SpriteSheetLoader, cls).__new__(cls)
            cls._instance.initialized = False
        return cls._instance

    def initialize(self):
        if self.initialized:
            return
        base_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

        sheet_dir = os.path.join(base_dir, "assets", "sheets")

        # 1. Load Sprite Sheet Images
        sheet_files = [
            "tiles.png", "items.png", "monsters.png", "rogues.png",
            "animated-tiles.png", "autotiles.png", "animals.png"
        ]

        for sf in sheet_files:
            path = os.path.join(sheet_dir, sf)
            if os.path.exists(path):
                try:
                    self._sheets[sf] = pygame.image.load(path).convert_alpha()
                except Exception as e:
                    print(f"[SpriteSheetLoader] Error loading {sf}: {e}")

        # 2. Parse TXT Mapping Files directly
        txt_pairs = [
            ("monsters.png", "monsters.txt"),
            ("items.png", "items.txt"),
            ("tiles.png", "tiles.txt"),
            ("rogues.png", "rogues.txt"),
            ("animals.png", "animals.txt"),
            ("animated-tiles.png", "animated-tiles.txt"),
            ("autotiles.png", "autotiles.txt"),
        ]

        for sheet_name, txt_name in txt_pairs:
            txt_path = os.path.join(sheet_dir, txt_name)
            if os.path.exists(txt_path):
                self._parse_txt_mapping(sheet_name, txt_path)

        self._load_assets(base_dir)

        # 3. Setup standard game semantic aliases
        self._register_default_aliases()

        self.initialized = True

    def _load_assets(self, base_dir: str):
        """Loads pre-built sprites from assets/ (generated by tools/build_assets.py)."""
        tile_dir = os.path.join(base_dir, "assets", "tiles")
        if os.path.isdir(tile_dir):
            for fn in os.listdir(tile_dir):
                if fn.endswith(".png"):
                    self._tiles[fn[:-4]] = pygame.image.load(os.path.join(tile_dir, fn)).convert_alpha()

        boss_dir = os.path.join(base_dir, "assets", "bosses")
        if os.path.isdir(boss_dir):
            for fn in sorted(os.listdir(boss_dir)):
                m = re.match(r"^(.+)_(\d+)\.png$", fn)
                if m:
                    surf = pygame.image.load(os.path.join(boss_dir, fn)).convert_alpha()
                    self._boss_frames.setdefault(m.group(1), []).append(surf)

    def get_asset_tile(self, name: str) -> pygame.Surface | None:
        return self._tiles.get(name)

    def has_boss_sprite(self, name: str) -> bool:
        return name in self._boss_frames

    def get_boss_frames(self, name: str) -> dict[str, list[pygame.Surface]]:
        """Animation dict for a hand-drawn boss (3 idle frames reused for every state)."""
        cache_key = f"anim_boss_{name}"
        if cache_key in self._cache:
            return self._cache[cache_key]

        idle = self._boss_frames[name]
        base = idle[0]
        size = base.get_size()

        telegraph = base.copy()
        glow = pygame.Surface(size, pygame.SRCALPHA)
        pygame.draw.circle(glow, (255, 40, 40, 110), (size[0] // 2, size[1] // 2), size[0] // 2)
        telegraph.blit(glow, (0, 0))

        flash = base.copy()
        flash.fill((200, 200, 200, 0), special_flags=pygame.BLEND_RGB_ADD)

        dead = base.copy()
        dead.fill((90, 90, 90, 255), special_flags=pygame.BLEND_RGBA_MULT)

        frames = {
            "idle": list(idle),
            "walk": list(idle),
            "attack": [idle[1 % len(idle)], idle[2 % len(idle)], idle[1 % len(idle)], base],
            "telegraph": [telegraph],
            "hurt": [flash],
            "dead": [dead],
        }
        self._cache[cache_key] = frames
        return frames

    def _parse_txt_mapping(self, sheet_name: str, txt_path: str):
        """
        Parses TXT format:
        e.g. '1.a. orc', '1.f. goblin archer', '20.b. red potion', '18.a. chest (closed)'
        Matches row (1-indexed) and col_letter ('a'=0, 'b'=1...) and sprite name.
        """
        # Regex matching: 1.a. orc, 17.c. framed door 1 (shut), 25.e. bottle of water, 6.f. warlock
        pattern_letter = re.compile(r"^(\d+)\.([a-zA-Z])\.\s*(.+)$")
        # Regex matching: 1. brazier (unlit)
        pattern_num = re.compile(r"^(\d+)\.\s*(.+)$")

        try:
            with open(txt_path, "r", encoding="utf-8") as f:
                for line in f:
                    line = line.strip()
                    if not line:
                        continue

                    m_let = pattern_letter.match(line)
                    if m_let:
                        row = int(m_let.group(1))
                        col = ord(m_let.group(2).lower()) - ord('a')
                        raw_name = m_let.group(3).strip()
                        self._register_name_mapping(raw_name, sheet_name, row, col)
                        continue

                    m_num = pattern_num.match(line)
                    if m_num:
                        row = int(m_num.group(1))
                        col = 0
                        raw_name = m_num.group(2).strip()
                        self._register_name_mapping(raw_name, sheet_name, row, col)
        except Exception as e:
            print(f"[SpriteSheetLoader] Error parsing {txt_path}: {e}")

    def _register_name_mapping(self, raw_name: str, sheet_name: str, row: int, col: int):
        """Registers all variations and sub-names of a sprite definition."""
        loc = (sheet_name, row, col)

        # Store exact lower and clean variations
        names_to_add = [raw_name.lower()]

        # Split slash variants (e.g. "lizardfolk / kobold (reptile)", "hag/witch")
        if "/" in raw_name:
            for part in raw_name.split("/"):
                p_clean = part.strip().lower()
                if p_clean:
                    names_to_add.append(p_clean)

        # Remove parentheses notes (e.g. "chest (closed)" -> "chest closed", "chest")
        no_parens = re.sub(r"[\(\)]", "", raw_name).strip().lower()
        names_to_add.append(no_parens)

        for name in names_to_add:
            slug1 = name
            slug2 = name.replace(" ", "_").replace("-", "_")
            slug3 = re.sub(r"[^a-z0-9]", "", name)

            if slug1 not in self._name_to_loc:
                self._name_to_loc[slug1] = loc
            if slug2 not in self._name_to_loc:
                self._name_to_loc[slug2] = loc
            if slug3 not in self._name_to_loc:
                self._name_to_loc[slug3] = loc

